# This script registers an external UserApplication with a Rendering Engine
# environment.
#
# The registration is stored in the machine-local Local/ directory and is
# therefore not committed to the Rendering Engine repository.
#
# Usage:
#   python3 register_project.py <ProjectPath>

import os
import sys


SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ENGINE_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, "..", ".."))

LOCAL_DIR = os.path.join(ENGINE_ROOT, "Local")
REGISTRY_FILE = os.path.join(LOCAL_DIR, "registered_projects.cmake")


def normalize_path(path):
    """
    @brief Convert a path to an absolute CMake-friendly path.

    @param path  Path to normalize.

    @return Absolute normalized path using forward slashes.
    """
    return os.path.abspath(path).replace("\\", "/")


def read_registered_projects():
    """
    @brief Read external UserApplication paths from the local registry.

    @return List of registered project paths.
    """
    if not os.path.exists(REGISTRY_FILE):
        return []

    projects = []

    with open(REGISTRY_FILE, "r") as registry_file:
        for line in registry_file:
            line = line.strip()

            if line.startswith('"') and line.endswith('"'):
                projects.append(line[1:-1])

    return projects


def write_registered_projects(projects):
    """
    @brief Write external UserApplication paths to the local registry.

    @param projects  List of registered project paths.
    """
    os.makedirs(LOCAL_DIR, exist_ok=True)

    with open(REGISTRY_FILE, "w") as registry_file:
        registry_file.write(
            "# This file is generated by register_project.py.\n"
            "# Machine-local Rendering Engine application registrations.\n"
            "\n"
            "set(RE_EXTERNAL_APPLICATIONS\n"
        )

        for project in projects:
            registry_file.write(f'    "{project}"\n')

        registry_file.write(")\n")


def write_project_engine_config(project_path):
    """
    @brief Write the machine-local Rendering Engine configuration
           for a UserApplication.

    @param project_path  Path to the UserApplication.
    """
    local_dir = os.path.join(project_path, "Local")
    config_file = os.path.join(local_dir, "rendering_engine.cmake")

    os.makedirs(local_dir, exist_ok=True)

    engine_root = normalize_path(ENGINE_ROOT)

    with open(config_file, "w") as config:
        config.write(
            "# This file is generated by register_project.py.\n"
            "# Machine-local Rendering Engine configuration.\n"
            "\n"
            "set(RENDERING_ENGINE_ROOT\n"
            f'    "{engine_root}"\n'
            ")\n"
        )

    return config_file


def register_project(project_path):
    """
    @brief Register an external UserApplication with this Rendering Engine.

    @param project_path  Path to the UserApplication.
    """
    project_path = normalize_path(project_path)

    if not os.path.isdir(project_path):
        print(f"Error: Project directory does not exist: '{project_path}'.")
        return False

    cmake_file = os.path.join(project_path, "CMakeLists.txt")

    if not os.path.isfile(cmake_file):
        print(
            f"Error: Project '{project_path}' does not contain "
            "a CMakeLists.txt file."
        )
        return False

    projects = read_registered_projects()

    if project_path not in projects:
        projects.append(project_path)
        write_registered_projects(projects)
        print(f"Registered project: {project_path}")
    else:
        print(f"Project is already registered: {project_path}")

    project_config = write_project_engine_config(project_path)

    print(f"Project configuration: {project_config}")
    print(f"Registration file: {REGISTRY_FILE}")

    return True


if __name__ == "__main__":
    if len(sys.argv) != 2:
        print("Usage: register_project.py <ProjectPath>")
        sys.exit(1)

    if not register_project(sys.argv[1]):
        sys.exit(1)
